    /**
     * Resolves localized name for a scrap dealer / recycler.
     */
    fun getLocalizedRecyclerName(recyclerId: String, langCode: String): String {
        val dict = RECYCLER_TRANSLATIONS[recyclerId] ?: return "Recycler Yard"
        return dict[langCode] 
            ?: dict["hi"]?.takeIf { isHindiDialect(langCode) }
            ?: dict["en"] 
            ?: "Recycler Yard"
    }

    /**
     * Resolves localized facility description for a recycler.
     */
    fun getLocalizedFacilityType(recyclerId: String, langCode: String): String {
        val dict = FACILITY_TRANSLATIONS[recyclerId] ?: return "Certified Scrap Yard"
        return dict[langCode]
            ?: dict["hi"]?.takeIf { isHindiDialect(langCode) }
            ?: dict["en"]
            ?: "Certified Scrap Yard"
    }

    /**
     * Resolves localized category name.
     */
    fun getLocalizedCategoryName(category: MaterialCategory, langCode: String): String {
        val dict = CATEGORY_TRANSLATIONS[category] ?: return category.name
        return dict[langCode]
            ?: dict["hi"]?.takeIf { isHindiDialect(langCode) }
            ?: dict["en"]
            ?: category.name
    }

    /**
     * Resolves localized name for a scrap material / product.
     */
    fun getLocalizedMaterialName(materialId: String, langCode: String): String {
        val dict = MATERIAL_TRANSLATIONS[materialId]
        if (dict != null) {
            val translated = dict[langCode]
                ?: dict["hi"]?.takeIf { isHindiDialect(langCode) }
                ?: dict["en"]
            if (!translated.isNullOrBlank()) return translated
        }

        // Fallback: look up in ALL_MATERIALS and synthesize via category
        val fallbackMat = Material.getById(materialId)
        if (fallbackMat != null) {
            if (langCode == "en" || langCode == "en_IN") return fallbackMat.name
            // If we have category translation, prefix appropriately
            val catName = getLocalizedCategoryName(fallbackMat.category, langCode)
            return when {
                materialId.contains("copper", ignoreCase = true) -> getLocalizedMaterialName("copper_wires_pipes", langCode)
                materialId.contains("brass", ignoreCase = true) -> getLocalizedMaterialName("brass_utensils_fittings", langCode)
                materialId.contains("iron", ignoreCase = true) || materialId.contains("steel", ignoreCase = true) -> getLocalizedMaterialName("iron_loha_scrap", langCode)
                materialId.contains("paper", ignoreCase = true) || materialId.contains("book", ignoreCase = true) -> getLocalizedMaterialName("books_white_paper", langCode)
                materialId.contains("carton", ignoreCase = true) || materialId.contains("cardboard", ignoreCase = true) -> getLocalizedMaterialName("cardboard_carton_gutta", langCode)
                materialId.contains("plastic", ignoreCase = true) || materialId.contains("bottle", ignoreCase = true) -> getLocalizedMaterialName("pet_bottles_water_soda", langCode)
                materialId.contains("battery", ignoreCase = true) -> getLocalizedMaterialName("lead_batteries_inverter_vehicle", langCode)
                materialId.contains("circuit", ignoreCase = true) || materialId.contains("pcb", ignoreCase = true) -> getLocalizedMaterialName("mixed_circuit_boards", langCode)
                materialId.contains("tyre", ignoreCase = true) || materialId.contains("rubber", ignoreCase = true) -> getLocalizedMaterialName("fibre_tyres_rubber", langCode)
                else -> "${catName}: ${fallbackMat.name}"
            }
        }

        return materialId.replace("_", " ").capitalizeWords()
    }

    private fun isHindiDialect(code: String): Boolean {
        return code in listOf("bho", "mwr", "hne", "bgc", "mai", "doi")
    }

    private fun String.capitalizeWords(): String {
        return split(" ").joinToString(" ") { word ->
            word.lowercase().replaceFirstChar { if (it.isLowerCase()) it.titlecase() else it.toString() }
        }
    }
}

