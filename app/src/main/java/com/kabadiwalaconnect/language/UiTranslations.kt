    fun get(key: String, langCode: String, vararg args: Any): String {
        val entry = DICTIONARY[key] ?: return key
        val direct = entry[langCode]
        val result = when {
            !direct.isNullOrBlank() -> direct
            isHindiDialect(langCode) -> entry["hi"] ?: entry["en"] ?: key
            else -> entry["hi"] ?: entry["en"] ?: key
        }
        return if (args.isNotEmpty()) {
            try {
                result.format(*args)
            } catch (e: Exception) {
                result
            }
        } else {
            result
        }
    }

    private fun isHindiDialect(code: String): Boolean {
        return code in listOf("bho", "mwr", "hne", "bgc", "mai", "doi")
    }
