 * Reactive Compose string accessor for UI buttons and labels.
 */
@Composable
fun localizedUi(key: String, vararg args: Any): String {
    val currentLang = LocalCurrentLanguage.current.code
    return UiTranslations.get(key, currentLang, *args)
